import { Client, Wallet } from "xrpl";
import { encode, encodeForSigning } from "ripple-binary-codec";
import { sign as kpSign } from "ripple-keypairs";
import { NET, txUrl } from "./config.mjs";
import { loadAccounts } from "./raw-submit.mjs";
const A = "B6D108A2839F33EB5AC78144C7495C685866276E2C23B0180929631ADC4BF123";
const BRK = "069AD8F844F462A8BAEF6195D7C4831D795E87B4A5F53E61EEAAF656201BB74E";
const log = (...a) => console.log(...a);
const signRaw = (tx, w) => { const t = { ...tx, SigningPubKey: w.publicKey };
  t.TxnSignature = kpSign(encodeForSigning(t), w.privateKey); return encode(t); };
const c = new Client(NET.wss, { connectionTimeout: 20000 }); await c.connect();
const { spare } = loadAccounts(); const sw = Wallet.fromSeed(spare.seed);
const send = async (tx, label) => {
  try { const p = await c.autofill({ Account: sw.address, ...tx });
    const r = await c.submitAndWait(signRaw(p, sw));
    log(`  ${label.padEnd(26)} ${r.result.meta.TransactionResult}`);
    log(`    ${txUrl(r.result.hash)}`); return r.result.meta.TransactionResult;
  } catch (e) { log(`  ${label.padEnd(26)} rejet: ${e.message}`); return "throw"; } };
await send({ TransactionType: "LoanBrokerDelete", LoanBrokerID: BRK }, "LoanBrokerDelete");
await send({ TransactionType: "VaultDelete", VaultID: A }, "VaultDelete A");
const ai = await c.request({ command: "account_info", account: sw.address, ledger_index: "validated" });
log(`\nspare : ${(Number(ai.result.account_data.Balance) / 1e6).toFixed(6)} XRP · OwnerCount ${ai.result.account_data.OwnerCount}`);
await c.disconnect();
